import { getSocket } from "../utils/socket.js";
import { initLocalVideo, addParticipantVideo } from "./session-main.js";

const socket = getSocket();

// WebRTC stream connetion
const peerConnection = new RTCPeerConnection();

peerConnection.ontrack = (event) => {
    if (peerConnection) {
        if (event.streams && event.streams[0]){
            addParticipantVideo("remote", event.streams[0]);
        } else {
            let inBoundStream = new MediaStream();
            inBoundStream.addTrack(event.track);
            addParticipantVideo("remote", inBoundStream);
        }
    }
}

/*
 * Listens for local ICE candidates generated by the RTCPeerConnection
 * and transmits them to the remote peer via WebSockets.
*/
peerConnection.onicecandidate = (event) => {
  if (event.candidate) {
    socket.send(
      JSON.stringify({
        type: "candidate",
        candidate: event.candidate,
      }),
    );
  }
};

/**
 * Handles an incoming remote ICE candidate and adds it to the peer connection.
 * @param {RTCIceCandidateInit} candidate - The remote ICE candidate received from the signaling server.
 */
export async function handleCandidate(candidate) {
  const data = candidate;

  await peerConnection.addIceCandidate(data);
}


/**
 * Initiates the WebRTC connection process as the caller.
 * Captures local media tracks, attaches them to the peer connection,
 * creates an SDP offer, sets it locally, and transmits it via WebSocket.
 */
export async function establishRTCOffer() {
  if (peerConnection) {
    const localStream = await initLocalVideo();
    const tracks = localStream.getTracks();

    tracks.forEach((track) => {
      peerConnection.addTrack(track, localStream);
    });

    // Initiator: Creates an offer
    const offer = await peerConnection.createOffer();
    await peerConnection.setLocalDescription(offer);

    socket.send(
      JSON.stringify({
        type: "offer",
        offer: offer,
      }),
    );
  }
}

/**
 * Handles an incoming SDP offer as the answering peer.
 * Attaches local media tracks, applies the remote offer description,
 * generates an SDP answer, sets it locally, and sends it back to the caller.
 * 
 * @param {RTCSessionDescriptionInit} offer - The SDP offer received from the caller.
 */
export async function handleOffer(offer) {
  if (peerConnection) {
    const localStream = await initLocalVideo();
    const tracks = localStream.getTracks();

    tracks.forEach((track) => {
      peerConnection.addTrack(track, localStream);
    });

    await peerConnection.setRemoteDescription(offer);

    const answer = await peerConnection.createAnswer();
    await peerConnection.setLocalDescription(answer);

    socket.send(
      JSON.stringify({
        type: "answer",
        answer: answer,
      }),
    );
  }
}

/**
 * Completes the WebRTC handshake on the initiating peer's side.
 * Applies the received SDP answer from the remote peer to establish the peer-to-peer connection.
 * 
 * @param {RTCSessionDescriptionInit} answer - The SDP answer received from the remote peer.
 */
export async function handleAnswer(answer) {
  if (peerConnection) {
    await peerConnection.setRemoteDescription(answer);
  }
}
